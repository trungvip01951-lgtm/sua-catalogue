import re
def ten_moi(t):
    """CDL65-10-1 → CDLF65-1-1T ; CDL200-30-A-B → CDLF200-3-A-BT (số tầng nguồn ×10 → số tầng; thêm F, hậu tố T = 3 pha, như CDLF42 đã duyệt)."""
    m = re.fullmatch(r'CDL(\d+)-(\d)0((?:-[0-9AB]+)*)', t); assert m, t
    return f'CDLF{m.group(1)}-{m.group(2)}{m.group(3)}T'
